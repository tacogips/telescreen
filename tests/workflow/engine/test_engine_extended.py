@dataclass
class EngineRig:
    """Own one SQLite workflow engine and its worker for a test."""

    harness: SqliteHarness
    clock: FakeClock
    repository: WorkflowRepository
    service: WorkflowService
    queue: SqlTaskQueue
    engine: RunEngine
    worker: EngineWorker
    notifications: NotificationFake
    issues: RecordingIssuesFake

    async def close(self) -> None:
        await self.harness.close()


async def make_rig() -> EngineRig:
    """Create a fully wired in-memory engine with deterministic time."""
    harness: SqliteHarness = await make_sqlite_harness()
    clock: FakeClock = FakeClock(datetime(2026, 10, 9, tzinfo=UTC))
    audit: AuditFake = AuditFake([])
    repository: WorkflowRepository = WorkflowRepository()
    queue: SqlTaskQueue = SqlTaskQueue(clock)
    redactor: Redactor = Redactor.default()
    service: WorkflowService = WorkflowService(redactor, ConfigFake(), audit, clock, repository)
    resolver: ResolverFake = ResolverFake()
    notifications: NotificationFake = NotificationFake([])
    issues: RecordingIssuesFake = RecordingIssuesFake()
    executors: ExecutorRegistry = ExecutorRegistry()
    executors.register(ConditionExecutor())
    executors.register(EndExecutor())
    executors.register(WaitExecutor())
    executors.register(SendBackExecutor())
    executors.register(HumanTaskExecutor(notifications, queue, resolver, clock, redactor))
    executors.register(EvidenceUploadExecutor(notifications, queue, resolver, clock, redactor))
    engine: RunEngine = RunEngine(
        service,
        executors,
        queue,
        IssueReaderFake(),
        issues,
        IndexerFake([]),
        redactor,
        audit,
        clock,
        repository,
    )
    executors.register(SubWorkflowExecutor(engine))
    registry: TaskHandlerRegistry = TaskHandlerRegistry()
    registry.register(AdvanceStepHandler(harness.sessions, engine))
    registry.register(TimerFiredHandler(harness.sessions, engine))
    registry.register(ChildRunFinishedHandler(harness.sessions, repository, engine, clock))
    registry.register(
        SlaCheckHandler(
            harness.sessions,
            repository,
            queue,
            notifications,
            resolver,
            issues,
            audit,
            clock,
        )
    )
    worker: EngineWorker = EngineWorker(
        harness.sessions,
        queue,
        registry,
        Scheduler(harness.sessions, (EmptyProvider(),), clock),
        clock,
        "extended-worker",
        concurrency=1,
    )
    return EngineRig(
        harness, clock, repository, service, queue, engine, worker, notifications, issues
    )


async def upload_run(rig: EngineRig, source: str, issue_id: str | None = None) -> str:
    """Persist a workflow definition and start one run."""
    async with rig.harness.sessions.begin() as session:
        definition: WorkflowDefinitionRow = await rig.service.upload(
            session, SourceFormat.YAML, source, "member:test"
        )
        await rig.service.activate(session, definition.name, definition.version)
        run_id: str = await rig.engine.start_run(
            session, definition.id, issue_id, RunTrigger.MANUAL
        )
    return run_id


